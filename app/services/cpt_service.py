def is_valid_cpt_code(code: str) -> bool:
    """Validate if a code is a valid CPT or HCPCS code."""
    if not code: return False
    code_str = str(code).strip()
    if "-" in code_str: code_str = code_str.split("-")[0].strip()
    code_str = code_str.replace(" ", "").replace(".", "").replace("/", "")
    if not code_str: return False
    if len(code_str) < 4 or len(code_str) > 5: return False
    if not code_str.isalnum(): return False
    if len(code_str) == 5:
        if code_str.isdigit(): return True
        if code_str[0].isalpha() and code_str[1:].isdigit(): return True
        if len(code_str) >= 2 and code_str[0:2].isalpha() and code_str[2:].isdigit(): return True
    if len(code_str) == 4:
        if code_str[0].isalpha() and code_str[1:].isdigit(): return True
    return False

