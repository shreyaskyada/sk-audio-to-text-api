def _extract_procedure_from_transcription(transcription: str) -> str:
    """Extract procedure name from transcription using simple heuristics"""
    transcription_lower = transcription.lower()
    procedure_patterns = [
        r"(epidural[^.]*)", r"(injection[^.]*)", r"(physical therapy[^.]*)", r"(\bpt\b[^.]*)",
        r"(mri[^.]*)", r"(x-ray[^.]*)", r"(walking boot[^.]*)", r"(cam boot[^.]*)",
        r"(brace[^.]*)", r"(surgery[^.]*)", r"(arthroscopy[^.]*)"
    ]
    for pattern in procedure_patterns:
        match = re.search(pattern, transcription_lower, re.IGNORECASE)
        if match: return match.group(1).strip()
    return transcription[:200] if len(transcription) > 200 else transcription

